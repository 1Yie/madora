use std::sync::{OnceLock, RwLock};

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AppLocale {
    En,
    Ja,
    Ko,
    ZhCn,
}

static APP_LOCALE: OnceLock<RwLock<AppLocale>> = OnceLock::new();

fn locale_state() -> &'static RwLock<AppLocale> {
    APP_LOCALE.get_or_init(|| RwLock::new(detect_locale()))
}

fn detect_locale() -> AppLocale {
    sys_locale::get_locale()
        .as_deref()
        .and_then(parse_locale)
        .unwrap_or(AppLocale::En)
}

fn parse_locale(value: &str) -> Option<AppLocale> {
    let normalized = value.trim().to_ascii_lowercase();

    if normalized.starts_with("zh") {
        return Some(AppLocale::ZhCn);
    }
    if normalized.starts_with("en") {
        return Some(AppLocale::En);
    }
    if normalized.starts_with("ja") {
        return Some(AppLocale::Ja);
    }
    if normalized.starts_with("ko") {
        return Some(AppLocale::Ko);
    }

    None
}

pub fn set_locale(locale: &str) {
    let Some(parsed) = parse_locale(locale) else {
        return;
    };

    if let Ok(mut guard) = locale_state().write() {
        *guard = parsed;
    }
}

pub fn current_locale() -> AppLocale {
    locale_state()
        .read()
        .map(|guard| *guard)
        .unwrap_or(AppLocale::En)
}

pub fn t(key: &str) -> String {
    let translated = match current_locale() {
        AppLocale::En => en(key),
        AppLocale::Ja => ja(key),
        AppLocale::Ko => ko(key),
        AppLocale::ZhCn => zh_cn(key),
    };

    translated.or_else(|| en(key)).unwrap_or(key).to_string()
}

pub fn tf(key: &str, vars: &[(&str, &str)]) -> String {
    let mut text = t(key);

    for (name, value) in vars {
        text = text.replace(&format!("{{{name}}}"), value);
    }

    text
}

